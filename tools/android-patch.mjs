#!/usr/bin/env node
/**
 * Re-apply our customisations to the generated Android project.
 *
 * `npx cap add android` writes a stock project, so anything we change there would be lost
 * whenever it is regenerated. This script is idempotent and runs as part of `android:init`
 * and `android:sync`, which keeps the native project reproducible from a clean checkout --
 * and means android/ does not have to be committed.
 *
 * What it does:
 *   1. Adds a network security config: HTTPS stays mandatory for the public internet, but
 *      cleartext is allowed to localhost / 10.0.2.2 (the emulator's host) / private LAN
 *      ranges, so a self-hosted game night over http:// works without weakening the app.
 *   2. Keeps versionName in sync with package.json.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const APP = join(ROOT, 'android', 'app');
if (!existsSync(APP)) {
  console.error('android/ not found — run `npx cap add android` first (or `npm run android:init`).');
  process.exit(1);
}

// ---- 1. network security config ----
const XML_DIR = join(APP, 'src', 'main', 'res', 'xml');
mkdirSync(XML_DIR, { recursive: true });
writeFileSync(join(XML_DIR, 'network_security_config.xml'), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/android-patch.mjs. HTTPS is required everywhere except the local
     addresses below, so a LAN or emulator server can use http:// while a public server
     cannot silently fall back to it. -->
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="true">localhost</domain>
        <domain includeSubdomains="true">127.0.0.1</domain>
        <domain includeSubdomains="true">10.0.2.2</domain>   <!-- the host machine, from the emulator -->
        <domain includeSubdomains="true">192.168.0.0</domain>
        <domain includeSubdomains="true">192.168.1.0</domain>
    </domain-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors><certificates src="system" /></trust-anchors>
    </base-config>
</network-security-config>
`);

const manifestPath = join(APP, 'src', 'main', 'AndroidManifest.xml');
let manifest = readFileSync(manifestPath, 'utf8');
if (!manifest.includes('android:networkSecurityConfig')) {
  manifest = manifest.replace('<application', '<application\n        android:networkSecurityConfig="@xml/network_security_config"');
  writeFileSync(manifestPath, manifest);
  console.log('AndroidManifest.xml  + networkSecurityConfig');
} else {
  console.log('AndroidManifest.xml  already patched');
}

// ---- 2. versionName from package.json ----
const version = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version;
const gradlePath = join(APP, 'build.gradle');
let gradle = readFileSync(gradlePath, 'utf8');
const next = gradle.replace(/versionName\s+"[^"]*"/, `versionName "${version}"`);
if (next !== gradle) {
  writeFileSync(gradlePath, next);
  console.log(`build.gradle         versionName "${version}"`);
} else {
  console.log(`build.gradle         versionName already "${version}"`);
}
