#!/usr/bin/env node
/**
 * Bake the server address into the packaged app.
 *
 *   npm run set-server -- https://election.example.com
 *   npm run set-server -- https://api.example.com --web https://play.example.com
 *   npm run set-server -- --clear          # back to same-origin (the web build)
 *
 * Rewrites frontend/js/server-config.js, which index.html loads before app.js. The APK has no
 * server of its own, so without this (or the in-app setup screen) it has nothing to talk to.
 * --web is only needed when the API host and the host serving the web build differ: it is what
 * invite links point at, since a friend tapping a link needs the web build, not the API.
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'frontend', 'js', 'server-config.js');
const args = process.argv.slice(2);
const clear = args.includes('--clear');
const webAt = args.indexOf('--web');
const web = webAt === -1 ? '' : (args[webAt + 1] || '');
const server = clear ? '' : (args.find(a => !a.startsWith('--') && a !== web) || '');

const clean = u => String(u || '').trim().replace(/\/+$/, '');

if (!clear && !server) {
  console.error('usage: npm run set-server -- https://your-server.example.com [--web https://…]\n' +
                '       npm run set-server -- --clear');
  process.exit(1);
}
for (const [label, value] of [['server', server], ['--web', web]]) {
  if (value && !/^https?:\/\/[^\s/]+/i.test(value)) {
    console.error(`error: ${label} must be a full URL including http:// or https:// (got "${value}")`);
    process.exit(1);
  }
}

writeFileSync(OUT, `/**
 * Build-time server address. Generated by tools/set-server.mjs -- edit that call, not this file.
 * Empty means "same origin", which is correct for the web build and for uvicorn locally.
 */
window.__ELECTION_SERVER__ = ${JSON.stringify(clean(server))};   // API + WebSocket host
window.__ELECTION_WEB__ = ${JSON.stringify(clean(web))};      // where invite links point (defaults to the server)
`);

if (clear) {
  console.log('server-config.js cleared — the app will use its own origin (web build).');
} else {
  console.log(`server  : ${clean(server)}`);
  if (web) console.log(`invites : ${clean(web)}`);
  if (/^http:\/\//i.test(server)) {
    console.warn('\nwarning: Android blocks cleartext HTTP by default. An http:// server needs\n' +
                 '         android:usesCleartextTraffic="true" in the manifest — see MOBILE.md.');
  }
  console.log('\nnext: npm run android:apk');
}
